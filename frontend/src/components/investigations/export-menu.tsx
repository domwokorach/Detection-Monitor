import { useState } from 'react'
import { toast } from 'sonner'
import { ChevronDown, Download, FileDown, Files, ListChecks, Loader2, Table2 } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { DropdownMenu, DropdownMenuContent, DropdownMenuItem, DropdownMenuLabel, DropdownMenuSeparator, DropdownMenuTrigger } from '@/components/ui/dropdown-menu'
import { Progress } from '@/components/ui/progress'
import { londonShort } from '@/lib/time'
import { downloadExport, filterParams, type ExportScope, type Filters } from '@/services/investigations'

const MAX_IDS = 200
const item = 'cursor-pointer rounded-[5px] text-[13px]'

/** Download CSV control. Every option asks the backend to build the file from a database snapshot and audits it. */
export function ExportMenu({ filters, pageIds, selectedIds }: { filters: Filters; pageIds: string[]; selectedIds: string[] }) {
  const [busy, setBusy] = useState(false)

  async function run(scope: ExportScope) {
    if (busy) return
    const params = scope === 'filtered' ? filterParams(filters) : new URLSearchParams()
    if (scope === 'page') pageIds.forEach(i => params.append('ids', i))
    if (scope === 'selected') selectedIds.forEach(i => params.append('ids', i))
    setBusy(true)
    const id = toast.loading('Preparing export…', { description: <Progress className="mt-1.5 h-1" value={undefined} aria-label="Preparing export" /> })
    try {
      const r = await downloadExport(scope, params, p => {
        if (p) toast.loading('Generating export…', { id, description: <div className="mt-1.5 space-y-1"><Progress className="h-1" value={p.total ? Math.round(p.processed * 100 / p.total) : 0} aria-label="Export progress" /><span className="tech text-[10px]">{p.processed.toLocaleString('en-GB')} / {p.total.toLocaleString('en-GB')} rows</span></div> })
      })
      toast.success('CSV downloaded', { id, description: `${r.filename} · ${r.rows.toLocaleString('en-GB')} investigation${r.rows === 1 ? '' : 's'}${r.generatedAt ? ` · snapshot ${londonShort(r.generatedAt)}` : ''}` })
    } catch (e) {
      toast.error('Export failed', { id, description: e instanceof Error ? e.message : 'Unexpected error' })
    } finally { setBusy(false) }
  }

  const tooMany = selectedIds.length > MAX_IDS
  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button size="sm" disabled={busy} aria-label="Download CSV" className="group/dl gap-1.5 rounded-[5px] bg-primary text-primary-foreground transition-all duration-200 hover:shadow-[0_0_14px_-2px_var(--primary)]">
          {busy ? <Loader2 className="animate-spin" aria-hidden="true" /> : <Download className="transition-transform duration-200 group-hover/dl:translate-y-0.5 motion-reduce:transition-none" aria-hidden="true" />}
          Download CSV<ChevronDown className="size-3.5 opacity-70" aria-hidden="true" />
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-72 rounded-[5px] p-1.5">
        <DropdownMenuLabel className="text-[11px] font-normal text-muted-foreground">Point-in-time snapshot generated by the server. Every export is audited.</DropdownMenuLabel>
        <DropdownMenuSeparator />
        <DropdownMenuItem className={item} onSelect={() => void run('filtered')}><Table2 aria-hidden="true" />Export Filtered Investigations</DropdownMenuItem>
        <DropdownMenuItem className={item} disabled={!pageIds.length} onSelect={() => void run('page')}><FileDown aria-hidden="true" />Export Current Page<span className="tech ml-auto text-[10px] text-muted-foreground">{pageIds.length}</span></DropdownMenuItem>
        <DropdownMenuItem className={item} disabled={!selectedIds.length || tooMany} onSelect={() => void run('selected')}><ListChecks aria-hidden="true" />Export Selected Investigations<span className="tech ml-auto text-[10px] text-muted-foreground">{selectedIds.length}</span></DropdownMenuItem>
        {tooMany && <p className="px-2 pb-1 text-[10px] text-sev-med">Select at most {MAX_IDS} per export, or use the filtered export.</p>}
        <DropdownMenuSeparator />
        <DropdownMenuItem className={item} onSelect={() => void run('all')}><Files aria-hidden="true" />Export All Authorised Investigations</DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  )
}
