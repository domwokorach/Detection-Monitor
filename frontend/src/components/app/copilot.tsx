import { Bot, Info } from 'lucide-react'
import { Message, MessageAvatar, MessageContent, MessageGroup } from '@/components/ui/message'
import { Bubble, BubbleContent, BubbleGroup } from '@/components/ui/bubble'
import { Avatar, AvatarFallback } from '@/components/ui/avatar'
import type { AlertDetail } from '@/types'
import { money, titleCase } from '@/lib/format'

/**
 * Case Copilot: a deterministic, rule-based explanation of why the engine flagged this case.
 * It restates stored evidence only. It is NOT an LLM and invents nothing beyond the case record.
 */
export function Copilot({ alert, accountName }: { alert: AlertDetail; accountName?: string }) {
  const tx = alert.transaction
  const top = [...alert.matches].sort((a, b) => b.score - a.score)
  const steps: string[] = []
  if (top.some(m => m.rule_code.includes('VELOCITY'))) steps.push('Review the other payments from this account in the same window.')
  if (top.some(m => m.rule_code.includes('WATCHLIST'))) steps.push('Check the counterparty and destination against your sanctions and watchlist sources.')
  if (top.some(m => m.rule_code.includes('LARGE') || m.rule_code.includes('OUTFLOW'))) steps.push('Compare the amount with the account’s normal activity and stated purpose.')
  if (!steps.length) steps.push('Review the transaction details and counterparty history.')
  steps.push('Record your decision and rationale in the review note; it is written to the audit log.')

  return (
    <MessageGroup>
      <Message>
        <MessageAvatar><Avatar className="size-7"><AvatarFallback className="bg-primary/15 text-primary"><Bot className="size-4" aria-hidden="true" /></AvatarFallback></Avatar></MessageAvatar>
        <MessageContent>
          <BubbleGroup>
            <Bubble><BubbleContent>
              <p>This {tx.direction === 'DEBIT' ? 'outgoing' : 'incoming'} payment of <strong>{money(tx.amount, tx.currency)}</strong> {tx.direction === 'DEBIT' ? 'to' : 'from'} {tx.counterparty}{accountName ? ` on ${accountName}` : ''} scored <strong className="tnum">{alert.risk_score}/100</strong>.</p>
            </BubbleContent></Bubble>
            <Bubble><BubbleContent>
              {top.length ? (<><p className="mb-1.5">It matched {top.length} rule{top.length > 1 ? 's' : ''}:</p>
                <ul className="list-disc space-y-1 pl-4">{top.map(m => <li key={m.id}><span className="font-medium">{titleCase(m.rule_code)}</span> (+{m.score}): {m.reason}</li>)}</ul></>) : <p>No rule evidence was stored for this alert.</p>}
            </BubbleContent></Bubble>
            <Bubble><BubbleContent>
              <p className="mb-1.5">Suggested next steps:</p>
              <ol className="list-decimal space-y-1 pl-4">{steps.map(s => <li key={s}>{s}</li>)}</ol>
            </BubbleContent></Bubble>
          </BubbleGroup>
          <p className="flex items-center gap-1 text-[10px] text-subtle"><Info className="size-3" aria-hidden="true" />Rule-based summary of stored evidence, not generated by an AI model.</p>
        </MessageContent>
      </Message>
    </MessageGroup>
  )
}
